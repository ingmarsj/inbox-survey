// Generates supabase/seed-questions.sql from questions.json.
//
// The survey definition lives in questions.json. For Supabase it is stored in the
// survey_config table, where the survey_* functions read it to validate every answer.
// Run this script after editing questions.json, then run the generated SQL in the
// Supabase SQL editor (it is safe to run again: it replaces the stored definition).
//
// Usage: node scripts/build-supabase-sql.mjs

import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { loadConfig } from '../questions.js';

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
export const QUESTIONS_FILE = path.join(ROOT, 'questions.json');
export const SEED_FILE = path.join(ROOT, 'supabase', 'seed-questions.sql');

const QUOTE_TAG = '$survey_json$';

/** SQL that stores the given survey definition (an object read from questions.json). */
export function seedSql(config) {
  const json = JSON.stringify(config, null, 2);
  if (json.includes(QUOTE_TAG)) throw new Error(`questions.json must not contain ${QUOTE_TAG}`);
  return `-- Generated by scripts/build-supabase-sql.mjs from questions.json. Do not edit by hand.
-- Run it in the Supabase SQL editor after schema.sql, and again whenever questions.json changes.

insert into public.survey_config (id, config)
values (true, ${QUOTE_TAG}
${json}
${QUOTE_TAG}::jsonb)
on conflict (id) do update set config = excluded.config, updated_at = now();
`;
}

/** The SQL file as it should be checked in right now. */
export function currentSeedSql() {
  loadConfig(QUESTIONS_FILE); // refuse to generate from a broken questions.json
  return seedSql(JSON.parse(readFileSync(QUESTIONS_FILE, 'utf8')));
}

if (process.argv[1] && pathToFileURL(path.resolve(process.argv[1])).href === import.meta.url) {
  writeFileSync(SEED_FILE, currentSeedSql());
  console.log(`Wrote ${path.relative(ROOT, SEED_FILE)}`);
}
