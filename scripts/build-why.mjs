// Builds the production survey for https://why.inbokss.com/inbox-survey/.
//
// why.inbokss.com is a static GitHub Pages site (the INBOKSS/why repository), so the survey is
// published as a folder inside it, and the answers are stored in Supabase through the survey_*
// functions from supabase/schema.sql. The page only ever holds the project's publishable key.
//
// The output has this shape; copy the inbox-survey/ folder into the root of the site repository:
//   <outDir>/inbox-survey/index.html, results.html, *.js, style.css, config.js, img/...
//
// Usage: node scripts/build-why.mjs [outDir]   (default: dist-why)

import { cpSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
export const PROJECT_FILE = path.join(ROOT, 'supabase', 'project.json');
export const SITE_FOLDER = 'inbox-survey';

/** The files of the survey that run in the browser against Supabase (no server, no demo, no questions.json). */
const FILES = [
  'index.html',
  'results.html',
  'app.js',
  'results.js',
  'aggregate.js',
  'validate.js',
  'supabase-api.js',
  'style.css',
];

/** Only the public project URL and a publishable (anon) key may end up in a web page. */
export function checkProject({ url, publishableKey }) {
  if (!/^https:\/\/[a-z0-9]+\.supabase\.co$/.test(url ?? '')) {
    throw new Error('supabase/project.json: "url" must look like https://<project-ref>.supabase.co');
  }
  const key = publishableKey ?? '';
  const isPublishable = key.startsWith('sb_publishable_');
  let isAnonJwt = false;
  if (/^eyJ[\w-]+\.[\w-]+\.[\w-]+$/.test(key)) {
    try {
      isAnonJwt = JSON.parse(Buffer.from(key.split('.')[1], 'base64url').toString('utf8')).role === 'anon';
    } catch {
      isAnonJwt = false;
    }
  }
  if (!isPublishable && !isAnonJwt) {
    throw new Error('supabase/project.json: "publishableKey" must be the publishable (or legacy anon) key, never a secret or service_role key');
  }
}

export function buildWhy(outDir = path.join(ROOT, 'dist-why'), project = JSON.parse(readFileSync(PROJECT_FILE, 'utf8'))) {
  checkProject(project);

  const target = path.join(outDir, SITE_FOLDER);
  rmSync(outDir, { recursive: true, force: true });
  mkdirSync(target, { recursive: true });

  for (const file of FILES) cpSync(path.join(ROOT, 'public', file), path.join(target, file));
  cpSync(path.join(ROOT, 'public', 'img'), path.join(target, 'img'), { recursive: true });

  const config = { backend: 'supabase', supabaseUrl: project.url, publishableKey: project.publishableKey };
  writeFileSync(
    path.join(target, 'config.js'),
    `// Generated by scripts/build-why.mjs. Public values only: never put a secret key here.\nwindow.SURVEY_CONFIG = ${JSON.stringify(config, null, 2)};\n`,
  );
  return target;
}

if (process.argv[1] && pathToFileURL(path.resolve(process.argv[1])).href === import.meta.url) {
  const target = buildWhy(process.argv[2] ? path.resolve(process.argv[2]) : undefined);
  console.log(`Survey for why.inbokss.com built in ${target}`);
}
